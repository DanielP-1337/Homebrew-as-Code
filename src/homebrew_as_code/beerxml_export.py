"""Offline BeerXML 1.0 exporter with strict, explicit input requirements.

No guessed brewhouse efficiency, fermenter volume, malt yields/colors or yeast
characteristics. A draft lacking those inputs is NOT import-ready.
"""
from __future__ import annotations

import math
import xml.etree.ElementTree as ET
from collections import defaultdict
from typing import Any

from .recipe import validate_recipe


class BeerXmlError(ValueError):
    """Input is not safe to represent in BeerXML."""


def _text(parent: ET.Element, tag: str, value: Any) -> ET.Element:
    node = ET.SubElement(parent, tag)
    node.text = str(value)
    return node


def _float(value: Any, field: str, low: float = 0, high: float = 1e9) -> float:
    if isinstance(value, bool) or not isinstance(value, (float, int)) or not math.isfinite(value):
        raise BeerXmlError(f"{field} must be a finite number")
    value = float(value)
    if not low <= value <= high:
        raise BeerXmlError(f"{field} must be between {low} and {high}")
    return value


def _add_fermentable(parent: ET.Element, name: str, amount_kg: float, kind: str,
                     specification: dict[str, Any] | None, missing: list[str]) -> None:
    node = ET.SubElement(parent, "FERMENTABLE")
    for tag, value in (("NAME", name), ("VERSION", 1), ("TYPE", kind), ("AMOUNT", amount_kg)):
        _text(node, tag, value)
    if specification is None:
        missing.append(f"fermentables.{name}: YIELD (%) and COLOR (SRM) required")
        return
    _text(node, "YIELD", _float(specification.get("yield_percent"), f"{name}.yield_percent", 0, 100))
    _text(node, "COLOR", _float(specification.get("color_srm"), f"{name}.color_srm", 0, 10000))


def _extract_parameters(params: dict[str, Any] | None, grains: list[dict[str, Any]]) -> tuple[dict[str, Any], list[str]]:
    p = params or {}
    missing: list[str] = []
    if not isinstance(p, dict):
        raise BeerXmlError("parameters must be a mapping")
    required = ("brewer", "batch_size_l", "boil_size_l", "efficiency_percent")
    for field in required:
        if field not in p:
            missing.append(f"parameters.{field}: required")
    if "brewer" in p and (not isinstance(p["brewer"], str) or not p["brewer"].strip()):
        raise BeerXmlError("brewer must be nonempty text")
    for field in ("batch_size_l", "boil_size_l"):
        if field in p:
            _float(p[field], field, 0.001, 100000)
    if "efficiency_percent" in p:
        _float(p["efficiency_percent"], "efficiency_percent", 0.001, 100)
    malt_specs = p.get("malts", {})
    if not isinstance(malt_specs, dict):
        raise BeerXmlError("parameters.malts must be a mapping")
    for g in grains:
        if g["name"] not in malt_specs:
            missing.append(f"parameters.malts.{g['name']}: yield_percent and color_srm required")
        elif not isinstance(malt_specs[g["name"]], dict):
            raise BeerXmlError("Each malt specification must be a mapping")
    yeast = p.get("yeast", {})
    if not isinstance(yeast, dict):
        raise BeerXmlError("parameters.yeast must be a mapping")
    for key in ("type", "form"):
        if not yeast.get(key):
            missing.append(f"parameters.yeast.{key}: required")
    if yeast.get("type") and yeast["type"] not in {"Ale", "Lager", "Wheat", "Wine", "Champagne"}:
        raise BeerXmlError("Unsupported BeerXML yeast type")
    if yeast.get("form") and yeast["form"] not in {"Liquid", "Dry", "Slant", "Culture"}:
        raise BeerXmlError("Unsupported BeerXML yeast form")
    return p, missing


def build_beerxml(recipe: dict[str, Any], parameters: dict[str, Any] | None = None) -> tuple[bytes, dict[str, Any]]:
    """Create BeerXML document and sidecar report; no network and no file writes."""
    validate_recipe(recipe)
    p, missing = _extract_parameters(parameters, recipe["fermentables"])
    root = ET.Element("RECIPES")
    r = ET.SubElement(root, "RECIPE")
    _text(r, "NAME", recipe["recipe"]["name"])
    _text(r, "VERSION", 1)
    _text(r, "TYPE", "All Grain")
    _text(r, "NOTES", "Generated by Homebrew-as-Code; review import before brewing")
    for key, tag in (("brewer", "BREWER"), ("batch_size_l", "BATCH_SIZE"),
                     ("boil_size_l", "BOIL_SIZE"), ("efficiency_percent", "EFFICIENCY")):
        if key in p:
            _text(r, tag, p[key])
    boil = recipe["boil"]
    boil_duration = _float(boil["duration_min"], "boil.duration_min", 1, 180)
    _text(r, "BOIL_TIME", boil_duration)
    _text(r, "OG", f'{float(recipe["targets"]["original_gravity_plato"]):g} P')
    _text(r, "ABV", float(recipe["targets"]["alcohol_abv_percent"]))
    _text(r, "IBU", float(recipe["targets"]["bitterness_ibu"]))
    fermentables = ET.SubElement(r, "FERMENTABLES")
    spec = p.get("malts", {})
    for grain in recipe["fermentables"]:
        _add_fermentable(fermentables, grain["name"], grain["amount_g"] / 1000, "Grain", spec.get(grain["name"]), missing)
    hops = ET.SubElement(r, "HOPS")
    miscs = ET.SubElement(r, "MISCS")
    addition_count = defaultdict(int)
    for addition in recipe["boil"].get("additions", []):
        t = _float(addition["remaining_min"], "remaining_min", 0, boil_duration)
        name = addition["ingredient"]
        mass = _float(addition["amount_g"], f"{name}.amount_g", 0.000001)
        if "alpha_acid_percent" in addition:
            h = ET.SubElement(hops, "HOP")
            for tag, value in (("NAME", name), ("VERSION", 1), ("ALPHA", _float(addition["alpha_acid_percent"], "alpha", 0, 100)),
                               ("AMOUNT", mass / 1000), ("USE", "Boil"), ("TIME", t)):
                _text(h, tag, value)
            addition_count["hops"] += 1
        elif "honey" in name.casefold():
            honey_cfg = p.get("honey", {})
            if honey_cfg and not isinstance(honey_cfg, dict):
                raise BeerXmlError("parameters.honey must be a mapping")
            _add_fermentable(fermentables, name, mass / 1000, "Sugar", honey_cfg or None, missing)
            # BeerXML fermentables store time with ADD_AFTER_BOIL/NOTES but cannot
            # represent a precise boil addition time. Preserve that in notes only.
            honey_node = fermentables[-1]
            _text(honey_node, "NOTES", f"Add with {t:g} minutes remaining in boil (manual timing; BeerXML 1.0 cannot encode this directly)")
            addition_count["honey"] += 1
        else:
            m = ET.SubElement(miscs, "MISC")
            for tag, value in (("NAME", name), ("VERSION", 1), ("TYPE", "Spice"), ("USE", "Boil"),
                               ("TIME", t), ("AMOUNT", mass / 1000), ("AMOUNT_IS_WEIGHT", "TRUE")):
                _text(m, tag, value)
            addition_count["misc"] += 1
    yeasts = ET.SubElement(r, "YEASTS")
    yeast_config = p.get("yeast", {})
    if yeast_config.get("type") and yeast_config.get("form"):
        y = ET.SubElement(yeasts, "YEAST")
        for tag, value in (("NAME", recipe["yeast"]["name"]), ("VERSION", 1),
                           ("TYPE", yeast_config["type"]), ("FORM", yeast_config["form"]),
                           ("AMOUNT", recipe["yeast"]["amount_g"] / 1000), ("AMOUNT_IS_WEIGHT", "TRUE")):
            _text(y, tag, value)
    mash = ET.SubElement(r, "MASH")
    _text(mash, "NAME", "Braumeister 20 L mash")
    _text(mash, "VERSION", 1)
    mash_steps = ET.SubElement(mash, "MASH_STEPS")
    for s in recipe["mash"]["steps"]:
        step = ET.SubElement(mash_steps, "MASH_STEP")
        for tag, value in (("NAME", f'{s["temperature_c"]} C rest'), ("VERSION", 1), ("TYPE", "Temperature"),
                           ("STEP_TEMP", s["temperature_c"]), ("STEP_TIME", s["duration_min"])):
            _text(step, tag, value)
    missing.extend([
        "mash infusion water volumes (23 L mash / 5 L sparge) not represented as a calibrated water profile",
        "RO salts and pH targets not transferred",
        "spice-contact after flameout not transferred as an automatic step",
        "fermentation temperature range and keg carbonation settings require manual review",
        "honey exact boil time is in NOTES only; verify manually after MySpeidel import",
    ])
    xml = ET.tostring(root, encoding="utf-8", xml_declaration=True, short_empty_elements=True)
    complete = not any("required" in x for x in missing)
    return xml + b"\n", {
        "format": "homebrew-as-code/beerxml-export-report-v1",
        "beerxml_version": 1,
        "required_fields_supplied": complete,
        "import_candidate": complete,
        "myspeidel_import_verified": False,
        "manual_review_required": True,
        "missing_or_lossy": missing,
        "ingredient_counts": dict(addition_count),
        "note": "Import only via MySpeidel web UI as a new PRIVATE test recipe. No API writes.",
    }
