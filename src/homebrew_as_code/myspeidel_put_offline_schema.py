"""Read-only compatibility report of private GET backup vs documented PUT schemas.

No network, credentials, recipe values, or identities are emitted.
The local validator is conservative and may report unverified constraints.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .myspeidel_golden_validation import _issues
from .myspeidel_put_roundtrip import private_file, read_backup, safe_schema_path


def compare_backup(spec_path: str, backup_path: str) -> dict[str, Any]:
    source = Path(spec_path).resolve()
    # The OpenAPI spec itself may live under .local/vendor.
    if not source.is_file() or source.stat().st_size > 10_000_000:
        raise ValueError('Missing or oversized OpenAPI specification')
    spec = json.loads(source.read_text(encoding='utf-8'))
    _, recipe, _ = read_backup(private_file(backup_path, must_exist=True))
    if not isinstance(spec, dict) or not isinstance(spec.get('components'), dict):
        raise ValueError('Invalid OpenAPI specification')
    schemas = spec['components'].get('schemas')
    if not isinstance(schemas, dict):
        raise ValueError('Missing schema definitions')
    report: dict[str, Any] = {
        'format': 'homebrew-as-code/myspeidel-put-offline-compatibility-v1',
        'offline': True, 'upload_ready': False, 'results': [],
    }
    for name in ('recipe_v4', 'recipe_v5'):
        schema = schemas.get(name)
        if not isinstance(schema, dict):
            raise ValueError('Missing recipe version schema')
        errors, blocked = _issues(spec, schema, recipe, '$')
        # Only allowlisted schema locations: others counted, not exposed.
        safe_errors = [{'path': _safe_structural_path(spec, schema, item.get('path')),
                        'code': item.get('code') if item.get('code') in (
                            'type_mismatch', 'required_missing', 'enum_mismatch',
                            'minimum', 'maximum', 'pattern', 'minLength', 'maxLength'
                        ) else 'other'} for item in errors[:64]]
        type_conflicts = []
        for item in errors:
            if item.get('code') == 'type_mismatch':
                # Never expose dynamic map keys, IDs, or actual values.
                at = item.get('path', '')
                type_conflicts.append({
                    'index': len(type_conflicts) + 1,
                    'path': _safe_structural_path(spec, schema, at),
                    'field': _safe_static_field(spec, schema, at),
                    **_type_diagnostic(spec, schema, recipe, at),
                })
        report['results'].append({
            'schema': name, 'type_conflicts': type_conflicts,
            'schema_error_count': len(errors), 'error_count': len(errors),
            'unverified_count': len(blocked),
            'first_errors': safe_errors,
            'compatible_with_supported_checks': not errors and not blocked,
        })
    return report


def _json_type(value: Any) -> str:
    """Return a type label, never the value itself."""
    if value is None:
        return 'null'
    if isinstance(value, bool):
        return 'boolean'
    if isinstance(value, dict):
        return 'object'
    if isinstance(value, list):
        return 'array'
    if isinstance(value, str):
        return 'string'
    if isinstance(value, int):
        return 'integer'
    if isinstance(value, float):
        return 'number'
    return 'unknown'


def _type_diagnostic(spec: dict, root_schema: dict, recipe: dict, path: str) -> dict:
    """Traverse the schema and value in memory; export types only.

    Paths are generated by the validator, never sourced from a remote response.
    Map keys and indices are used only internally, never included in the report.
    """
    import re
    parts = re.findall(r'[^.\[\]]+|\[\d+\]', path[2:]) if path.startswith('$.') else []
    schema: Any = root_schema
    value: Any = recipe
    try:
        for part in parts:
            for _ in range(32):
                if not isinstance(schema, dict) or '$ref' not in schema:
                    break
                ref = schema['$ref']
                if not isinstance(ref, str) or not ref.startswith('#/components/schemas/'):
                    return {'expected': 'unknown', 'actual': 'unknown', 'nullable': False}
                schema = spec['components']['schemas'][ref.split('/')[-1]]
            else:
                return {'expected': 'unknown', 'actual': 'unknown', 'nullable': False}
            if part.startswith('['):
                value = value[int(part[1:-1])]
                schema = schema['items']
            else:
                value = value[part]
                schema = schema.get('properties', {}).get(part, schema.get('additionalProperties'))
        for _ in range(32):
            if not isinstance(schema, dict) or '$ref' not in schema:
                break
            ref = schema['$ref']
            if not isinstance(ref, str) or not ref.startswith('#/components/schemas/'):
                raise ValueError('invalid ref')
            schema = spec['components']['schemas'][ref.split('/')[-1]]
        if not isinstance(schema, dict):
            raise ValueError('invalid schema')
        expected = schema.get('type')
        return {'expected': expected if expected in ('string', 'integer', 'number', 'boolean', 'array', 'object') else 'unknown',
                'actual': _json_type(value), 'nullable': schema.get('nullable') is True}
    except (KeyError, IndexError, TypeError, ValueError, AttributeError):
        return {'expected': 'unknown', 'actual': 'unknown', 'nullable': False}


def _safe_static_field(spec: dict, root_schema: dict, path: str) -> str:
    """Reveal only a *schema-declared* property name, never a map key/value.

    A property is returned only if it is the final segment of a validator path
    and is explicitly declared in the resolved parent's `properties` object.
    Dynamic `additionalProperties` map keys cannot be reported as field names.
    """
    import re
    from .myspeidel_put_roundtrip import _SAFE_SEGMENTS

    if not isinstance(path, str) or not path.startswith('$.'):
        return 'redacted'
    parts = re.findall(r'[^.\[\]]+|\[\d+\]', path[2:])
    if not parts or '[' in parts[-1] or parts[-1] not in _SAFE_SEGMENTS:
        return 'redacted'

    schema: Any = root_schema
    try:
        for index, part in enumerate(parts):
            seen = set()
            while isinstance(schema, dict) and '$ref' in schema:
                ref = schema['$ref']
                if (not isinstance(ref, str)
                        or not ref.startswith('#/components/schemas/')
                        or ref in seen or len(seen) >= 32):
                    return 'redacted'
                seen.add(ref)
                schema = spec['components']['schemas'][ref.rsplit('/', 1)[-1]]
            if not isinstance(schema, dict):
                return 'redacted'
            if part.startswith('['):
                if schema.get('type') != 'array':
                    return 'redacted'
                schema = schema['items']
            else:
                props = schema.get('properties', {})
                if index == len(parts) - 1:
                    # Last element must be explicitly declared, not arbitrary map key.
                    return part if isinstance(props, dict) and part in props else 'redacted'
                schema = props[part] if isinstance(props, dict) and part in props else schema.get('additionalProperties')
        return 'redacted'
    except (KeyError, IndexError, TypeError, ValueError, AttributeError):
        return 'redacted'


def _safe_structural_path(spec: dict, root_schema: dict, path: Any) -> str:
    """Return a schema-verified path with every dynamic key redacted.

    Never echo path text originating outside declared schema properties. Array
    positions are represented as [*]; additionalProperties keys as <redacted>.
    Fail closed if a schema cannot be resolved or its shape is unexpected.
    """
    import re
    from .myspeidel_put_roundtrip import _SAFE_SEGMENTS

    if not isinstance(path, str) or not path.startswith('$.') or len(path) > 4096:
        return 'redacted'
    parts = re.findall(r'[^.\[\]]+|\[\d+\]', path[2:])
    if not parts or len(parts) > 64:
        return 'redacted'
    schema: Any = root_schema
    visible = ['$']
    try:
        for part in parts:
            seen: set[str] = set()
            while isinstance(schema, dict) and '$ref' in schema:
                ref = schema['$ref']
                if (not isinstance(ref, str)
                        or not ref.startswith('#/components/schemas/')
                        or ref in seen or len(seen) >= 32):
                    return 'redacted'
                seen.add(ref)
                schema = spec['components']['schemas'][ref.rsplit('/', 1)[-1]]
            if not isinstance(schema, dict):
                return 'redacted'
            if part.startswith('['):
                if schema.get('type') != 'array' or re.fullmatch(r'\[\d+\]', part) is None:
                    return 'redacted'
                visible.append('[*]')
                schema = schema['items']
                continue
            props = schema.get('properties', {})
            if isinstance(props, dict) and part in props and (part in _SAFE_SEGMENTS or part == 'water_types'):
                visible.append('.' + part)
                schema = props[part]
            elif isinstance(schema.get('additionalProperties'), dict):
                visible.append('.<redacted>')
                schema = schema['additionalProperties']
            else:
                return 'redacted'
        return ''.join(visible)
    except (KeyError, IndexError, TypeError, ValueError, AttributeError):
        return 'redacted'
